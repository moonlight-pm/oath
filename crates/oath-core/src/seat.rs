//! Single seat: Unix name `home`, HOME=/home. Root is privilege, not login.
//! `void` (R36) is the unprivileged account daemons drop to.

use std::collections::BTreeMap;
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::process::Command;

use crate::error::Result;
use crate::kinds::Host;

pub const NAME: &str = "home";
pub const UID: u32 = 1;
pub const GID: u32 = 1;
pub const HOME: &str = "/home";
pub const HELPERS: &str = "/lib/oath";
/// `home`'s login shell (R27), from `pkg:zsh`, which the base profile
/// fixes. Root's stays `/bin/sh`.
pub const SHELL: &str = "/bin/zsh";

/// The unprivileged account (R36): uid and gid 65534, the kernel's
/// overflow id. It owns no files and cannot log in (no key, no listed
/// shell); sshd, dhcpcd and chronyd drop to it, and a service may run as it.
pub const VOID: &str = "void";
pub const VOID_ID: u32 = 65534;
/// Its home: empty, root's, and the chroot sshd and dhcpcd use.
pub const VOID_HOME: &str = "/var/empty";

pub fn passwd_file() -> String {
    format!(
        "root:x:0:0:root:/root:/bin/sh\n{NAME}:x:{UID}:{GID}:{NAME}:{HOME}:{SHELL}\n\
         {VOID}:x:{VOID_ID}:{VOID_ID}:{VOID}:{VOID_HOME}:/bin/false\n"
    )
}

/// The login shells (getusershell); `void`'s `/bin/false` is not one.
pub fn shells_file() -> String {
    format!("/bin/sh\n/bin/bash\n{SHELL}\n")
}

pub fn group_file() -> String {
    format!("root:x:0:\n{NAME}:x:{GID}:\n{VOID}:x:{VOID_ID}:\n")
}

pub fn shadow_file() -> String {
    format!("root:*:1:0:99999:7:::\n{NAME}:*:1:0:99999:7:::\n{VOID}:*:1:0:99999:7:::\n")
}

pub fn write_side_effects(desired: &Host) -> Result<()> {
    let _ = fs::create_dir_all("/etc");
    fs::write("/etc/hostname", format!("{}\n", desired.hostname))?;
    fs::write("/etc/hosts", hosts_file(desired))?;
    write_profile(&login_env(desired))?;
    let _ = fs::create_dir_all("/etc/ssh");
    write_etc(crate::ssh::SSHD_CONFIG, &crate::ssh::sshd_config(&login_env(desired)))?;
    write_etc("/etc/zprofile", ZPROFILE)?;
    write_etc("/etc/zshrc", &zshrc(&desired.hostname))?;
    fs::write("/etc/shells", shells_file())?;
    Ok(())
}

/// `void`'s home: empty and root's (mode 0755), as sshd requires of its
/// privilege-separation chroot.
pub fn ensure_void_home() -> std::io::Result<()> {
    fs::create_dir_all(VOID_HOME)?;
    std::os::unix::fs::chown(VOID_HOME, Some(0), Some(0))?;
    fs::set_permissions(VOID_HOME, fs::Permissions::from_mode(0o755))
}

/// A login zsh reads `host:local` env as a login bash does.
pub const ZPROFILE: &str = "# generated by oath: host:local env, from /etc/profile\n\
                            emulate sh -c '. /etc/profile'\n";

/// `/etc/zshrc`: the prompt Joshua's own machine uses (time, user@host,
/// the last two directories, the git branch, `§`), with user@host and the
/// branch in this host's colors. History and keys as a bash user expects.
pub fn zshrc(hostname: &str) -> String {
    let (name, branch) = prompt_colors(hostname);
    format!(
        "# generated by oath from host:local (its hostname picks the prompt's color)\n\
         HISTFILE=~/.zsh_history\n\
         HISTSIZE=50000\n\
         SAVEHIST=50000\n\
         setopt hist_ignore_dups hist_ignore_space prompt_subst\n\
         bindkey -e\n\
         bindkey '^[[H' beginning-of-line '^[[1~' beginning-of-line '^[OH' beginning-of-line\n\
         bindkey '^[[F' end-of-line '^[[4~' end-of-line '^[OF' end-of-line\n\
         bindkey '^[[3~' delete-char\n\
         autoload -Uz compinit && compinit\n\
         \n\
         git_branch() {{\n\
         \x20 local b=$(git branch --show-current 2>/dev/null)\n\
         \x20 [[ -n $b ]] && print \" $b\"\n\
         }}\n\
         \n\
         PROMPT='%F{{#666666}}%* %F{{{name}}}%n@%m %F{{#cccccc}}%2~%F{{{branch}}}$(git_branch)%F{{#ffffff}} § '\n"
    )
}

/// The prompt's two colors for `hostname`: a hue from its hash, at the
/// saturation and lightness of the blue the prompt was drawn in (#3B9DC2
/// for user@host, #2A7A9E for the branch). Each machine keeps its own.
pub fn prompt_colors(hostname: &str) -> (String, String) {
    let hash =
        hostname.bytes().fold(0x811c_9dc5u32, |h, b| (h ^ u32::from(b)).wrapping_mul(0x0100_0193));
    let hue = f64::from(hash % 360);
    (hsl_hex(hue, 0.53, 0.50), hsl_hex(hue, 0.58, 0.39))
}

fn hsl_hex(h: f64, s: f64, l: f64) -> String {
    let c = (1.0 - (2.0 * l - 1.0).abs()) * s;
    let x = c * (1.0 - ((h / 60.0) % 2.0 - 1.0).abs());
    let (r, g, b) = match (h / 60.0) as u32 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    let m = l - c / 2.0;
    let byte = |v: f64| ((v + m) * 255.0).round() as u8;
    format!("#{:02X}{:02X}{:02X}", byte(r), byte(g), byte(b))
}

/// `/etc/hosts`: localhost, this hostname, then `host:local.hosts`.
pub fn hosts_file(host: &Host) -> String {
    let mut body = format!(
        "# generated by oath from host:local (oath set host:local hosts=...)\n\
         127.0.0.1 localhost\n::1 localhost\n127.0.1.1 {}\n",
        host.hostname
    );
    for (name, addr) in &host.hosts {
        body.push_str(&format!("{addr} {name}\n"));
    }
    body
}

/// A host name: letters, digits, `-` and `.`, at most `max` bytes, not
/// starting with `-` or `.`.
pub fn is_host_name(name: &str, max: usize) -> bool {
    !name.is_empty()
        && name.len() <= max
        && !name.starts_with(['-', '.'])
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '.')
}

/// `host:local.env` plus `TZ` from `timezone` (an explicit `env.TZ` wins).
pub fn login_env(host: &Host) -> BTreeMap<String, String> {
    let mut env = host.env.clone();
    let tz = host.timezone.trim();
    if !tz.is_empty() {
        env.entry("TZ".into()).or_insert_with(|| tz.to_string());
    }
    env
}

pub fn write_profile(env: &BTreeMap<String, String>) -> Result<()> {
    write_etc("/etc/profile", &profile_body(env))
}

/// A root-owned file every account reads.
fn write_etc(path: &str, body: &str) -> Result<()> {
    fs::write(path, body)?;
    let _ = fs::set_permissions(path, fs::Permissions::from_mode(0o644));
    let _ = Command::new("/bin/chown").args(["0:0", path]).status();
    Ok(())
}

pub fn profile_body(env: &BTreeMap<String, String>) -> String {
    let mut body = String::from(
        "# generated by oath from host:local env (root-owned; do not copy to $HOME)\n",
    );
    for (k, v) in env {
        if !valid_env_name(k) || v.contains('\n') || v.contains('\0') {
            continue;
        }
        body.push_str("export ");
        body.push_str(k);
        body.push('=');
        body.push_str(&sh_single_quote(v));
        body.push('\n');
    }
    body
}

pub fn valid_env_name(name: &str) -> bool {
    let mut cs = name.chars();
    match cs.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    cs.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn sh_single_quote(v: &str) -> String {
    format!("'{}'", v.replace('\'', "'\\''"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn home_is_uid_1() {
        assert_eq!(UID, 1);
        assert_eq!(GID, 1);
        assert!(passwd_file().contains("home:x:1:1:home:/home:/bin/zsh"));
        assert!(passwd_file().contains("root:x:0:0:root:/root:/bin/sh"));
        assert!(shells_file().lines().any(|l| l == "/bin/sh"));
        assert!(shells_file().lines().any(|l| l == SHELL));
        let g = group_file();
        assert!(g.contains("home:x:1:"));
        assert!(!g.contains("wheel"));
        assert!(!g.contains("video"));
        assert!(!g.contains("seat:"));
    }

    #[test]
    fn void_is_65534_with_no_login() {
        assert!(passwd_file().contains("void:x:65534:65534:void:/var/empty:/bin/false"));
        assert!(group_file().contains("void:x:65534:"));
        assert!(shadow_file().contains("void:*:"));
        assert!(!shells_file().contains("/bin/false"));
    }

    #[test]
    fn prompt_colors_follow_the_hostname() {
        let (name, branch) = prompt_colors("canto");
        assert_eq!(prompt_colors("canto"), (name.clone(), branch.clone()));
        assert_ne!(prompt_colors("oath").0, name);
        for c in [&name, &branch] {
            assert_eq!(c.len(), 7);
            assert!(c.starts_with('#') && c[1..].chars().all(|c| c.is_ascii_hexdigit()));
        }
        // The blues the prompt was drawn in, back from their hues.
        let near = |a: &str, b: &str| {
            (1..7).step_by(2).all(|i| {
                let ch = |s: &str| i32::from_str_radix(&s[i..i + 2], 16).unwrap();
                (ch(a) - ch(b)).abs() <= 3
            })
        };
        assert!(near(&hsl_hex(196.0, 0.53, 0.50), "#3B9DC2"));
        assert!(near(&hsl_hex(199.0, 0.58, 0.39), "#2A7A9E"));
        let rc = zshrc("canto");
        assert!(rc.contains(&format!("%F{{{name}}}%n@%m")));
        assert!(rc.contains(&format!("%F{{{branch}}}$(git_branch)")));
        assert!(rc.contains("§ '\n"));
        assert!(rc.contains("  local b=$(git branch --show-current 2>/dev/null)\n"));
    }

    #[test]
    fn profile_is_root_owned_copy() {
        let mut env = BTreeMap::new();
        env.insert("EDITOR".into(), "vi".into());
        let b = profile_body(&env);
        assert!(b.contains("host:local env"));
        assert!(b.contains("EDITOR='vi'"));
        assert!(!b.contains("/home"));
    }

    #[test]
    fn hosts_file_names_the_others_after_this_machine() {
        let mut host = Host {
            hostname: "canto".into(),
            power: crate::kinds::HostPower::Run,
            env: BTreeMap::new(),
            timezone: String::new(),
            hosts: BTreeMap::new(),
            origins: Vec::new(),
            profile: String::new(),
            publishers: Vec::new(),
            mounts: BTreeMap::new(),
            module_options: BTreeMap::new(),
        };
        host.hosts.insert("novus".into(), "10.0.0.5".into());
        host.hosts.insert("nas".into(), "fd00::12".into());
        let f = hosts_file(&host);
        assert!(f.starts_with("# generated by oath from host:local"), "{f}");
        assert!(f.contains("127.0.0.1 localhost\n::1 localhost\n127.0.1.1 canto\n"), "{f}");
        assert!(f.ends_with("fd00::12 nas\n10.0.0.5 novus\n"), "{f}");
        assert!(is_host_name("novus.lan", 253));
        assert!(!is_host_name("-novus", 253) && !is_host_name("no vus", 253));
        assert!(!is_host_name(&"a".repeat(64), 63));
    }

    #[test]
    fn timezone_becomes_tz_unless_env_sets_it() {
        let mut host = Host {
            hostname: "oath".into(),
            power: crate::kinds::HostPower::Run,
            env: BTreeMap::new(),
            timezone: "MST7MDT".into(),
            hosts: BTreeMap::new(),
            origins: Vec::new(),
            profile: String::new(),
            publishers: Vec::new(),
            mounts: BTreeMap::new(),
            module_options: BTreeMap::new(),
        };
        assert_eq!(login_env(&host).get("TZ").map(String::as_str), Some("MST7MDT"));
        host.env.insert("TZ".into(), "UTC".into());
        assert_eq!(login_env(&host).get("TZ").map(String::as_str), Some("UTC"));
        host.timezone.clear();
        host.env.clear();
        assert!(login_env(&host).get("TZ").is_none());
    }
}
