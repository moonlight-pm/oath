//! pkg:oath: the Oath binaries as a plan product. `cargo make build`
//! packs this tree (the workspace, and every crates.io crate in
//! Cargo.lock, fetched and checked against its checksum) into
//! `pkg:oath-src` and builds it in the sandbox with `pkg:rust`, the
//! vendor's Rust release pinned in pkgs/lock.json, linking with
//! `pkg:llvm`'s clang and musl. The build host's Rust
//! builds only oath-make itself. The product follows the tree, so it is
//! not locked; a tree that has not changed is not rebuilt.
//!
//! Product: `bin/oath`, `lib/oath/{init,serial-login,sudo}`,
//! `boot/BOOTX64.EFI` (oath-efi) and `components.json`.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use oath_core::{fmt_plan, PkgNeed, PlanFile};
use serde::{Deserialize, Serialize};

use crate::pkgs::{self, PkgToml, Source};
use crate::util::write_pretty;

const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// What the tree is packed from, relative to the repo.
const TREE: &[&str] =
    &["Cargo.toml", "Cargo.lock", ".cargo/config.toml", "crates", "brand/logo-white.png"];

#[derive(Default, Serialize, Deserialize)]
struct Built {
    plan: String,
    product: String,
}

/// Build pkg:oath from this tree (or reuse the last build of the same
/// plan) and return its tree in the build catalog.
pub fn build(repo: &Path) -> Result<PathBuf> {
    let cat = pkgs::build_catalog(repo)?;
    let lock = pkgs::read_lock(repo)?;
    let crates = fetch_crates(repo)?;
    let src = source_pack(repo, &cat, &crates)?;
    let version = version(repo)?;
    let mut build_needs = vec![PkgNeed { id: "pkg:oath-src".into(), hash: src.clone() }];
    for d in ["busybox", "llvm", "rust"] {
        build_needs.push(PkgNeed { id: format!("pkg:{d}"), hash: pkgs::product(&lock, d)? });
    }
    let script = format!(
        "# generated by cargo make build from crates/oath-make/src/oath-pkg.sh\n\
         SRC=/oath/store/pkg/oath-src/{src}/src\n\
         FILES=/oath/store/pkg/oath-src/{src}/files\n\
         VERSION={version}\n\
         {body}",
        body = include_str!("oath-pkg.sh"),
    );
    let plan = PlanFile {
        name: "oath".into(),
        produces: "pkg:oath".into(),
        build_needs,
        run_needs: Vec::new(),
        script,
    };
    let text = fmt_plan(&plan);
    let dir = repo.join("build/pkgs");
    fs::create_dir_all(&dir)?;
    let plan_path = dir.join("oath.plan");
    fs::write(&plan_path, &text)?;
    let plan_hash = oath_core::file_hash(text.as_bytes());
    let record = dir.join("oath.json");
    let last: Built = fs::read_to_string(&record)
        .ok()
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_default();
    let tree = |product: &str| cat.join("store/pkg/oath").join(product);
    if last.plan == plan_hash && tree(&last.product).is_dir() {
        eprintln!("== pkg:oath {} (cached)", last.product);
        return Ok(tree(&last.product));
    }
    eprintln!("== pkg:oath {version} building (pkg:rust {})", pkgs::product(&lock, "rust")?);
    let r =
        oath_core::build_file(&cat, &plan_path).map_err(|e| anyhow::anyhow!("pkg:oath: {e}"))?;
    eprintln!("== pkg:oath {}", r.product);
    write_pretty(&record, &Built { plan: plan_hash, product: r.product.clone() })?;
    Ok(tree(&r.product))
}

/// The workspace version (`crates/oath`).
fn version(repo: &Path) -> Result<String> {
    let text = fs::read_to_string(repo.join("crates/oath/Cargo.toml"))?;
    let v: toml::Value = toml::from_str(&text)?;
    v.get("package")
        .and_then(|p| p.get("version"))
        .and_then(|v| v.as_str())
        .map(str::to_string)
        .context("crates/oath/Cargo.toml has no package.version")
}

/// Every crate in Cargo.lock, from crates.io, verified by its checksum.
fn fetch_crates(repo: &Path) -> Result<Vec<(String, PathBuf)>> {
    let text = fs::read_to_string(repo.join("Cargo.lock"))?;
    let lock: toml::Value = toml::from_str(&text).context("parse Cargo.lock")?;
    let mut source = Vec::new();
    for p in lock.get("package").and_then(|p| p.as_array()).context("Cargo.lock has no packages")? {
        let field = |k: &str| p.get(k).and_then(|v| v.as_str());
        let (Some(name), Some(version)) = (field("name"), field("version")) else {
            bail!("Cargo.lock: package without name or version");
        };
        match field("source") {
            None => continue, // a workspace member
            Some(CRATES_IO) => {}
            Some(other) => bail!(
                "Cargo.lock: {name} {version} comes from {other}; only crates.io crates are packed"
            ),
        }
        let sum = field("checksum")
            .with_context(|| format!("Cargo.lock: {name} {version} has no checksum"))?;
        source.push(Source {
            url: format!("https://static.crates.io/crates/{name}/{name}-{version}.crate"),
            sha256: sum.to_string(),
            file: Some(format!("crates/{name}-{version}.crate")),
            ..Default::default()
        });
    }
    let pkg = PkgToml {
        source,
        unsigned: Some("crates.io crates are pinned by Cargo.lock's checksums".into()),
        ..Default::default()
    };
    pkgs::fetch(repo, &pkg)
}

/// `src/crates/*.crate` and `files/tree/` (the workspace, without
/// `target/`) into the store as pkg:oath-src.
fn source_pack(repo: &Path, cat: &Path, crates: &[(String, PathBuf)]) -> Result<String> {
    let stage = repo.join("build/pkgs/src/oath");
    let _ = fs::remove_dir_all(&stage);
    fs::create_dir_all(stage.join("src/crates"))?;
    for (rel, f) in crates {
        fs::copy(f, stage.join("src").join(rel))?;
    }
    let tree = stage.join("files/tree");
    for rel in TREE {
        copy_source(&repo.join(rel), &tree.join(rel))?;
    }
    pkgs::store(cat, "oath-src", &stage)
}

fn copy_source(from: &Path, to: &Path) -> Result<()> {
    if from.is_dir() {
        fs::create_dir_all(to)?;
        for e in fs::read_dir(from)? {
            let e = e?;
            if e.file_name() != "target" {
                copy_source(&e.path(), &to.join(e.file_name()))?;
            }
        }
    } else if from.is_file() {
        fs::create_dir_all(to.parent().context("parent")?)?;
        fs::copy(from, to).with_context(|| format!("copy {}", from.display()))?;
    } else {
        bail!("{} is missing", from.display());
    }
    Ok(())
}
