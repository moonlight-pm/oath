// Order: system and library headers, the generated protocol headers, forward
// declarations of every struct rv_*, then the area headers in the only order
// in which every by-value member is complete before use:
//
//   util.h    core: logging, timestamps, RV_ARRAY, slotmap
//   config.h  config: embedded by value in struct rv_input_device (seat)
//   output.h  output: struct rv_layer_shell_seat is embedded in struct rv_seat
//   core.h    core: struct rv_wm_node / rv_scene_saveable_surfaces embedded in struct rv_window
//   window.h  window: struct rv_window_ref is embedded in struct rv_seat
//   cursor.h  cursor: struct rv_cursor / rv_input_relay are embedded in struct rv_seat
//   seat.h    seat (+ the cursor area's struct rv_tablet, which embeds struct rv_input_device)
//   server.h  core: struct rv_server embeds a manager from every area
//
// Zig build_options.xwayland is WLR_HAS_XWAYLAND from <wlr/config.h>.

